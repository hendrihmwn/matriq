"""
Daily Quiz Bot (Telegram)

- Sends questions from output/quiz-YYYY-MM-DD.json (generated by the matriq-quiz skill)
  every weekday at the configured time.
- Questions are sent as Telegram quiz polls (answer & explanation shown automatically).
- Answers are recorded in SQLite for the leaderboard.

Commands:
  /start        - bot info
  /quiz         - send today's quiz now (manual)
  /leaderboard  - scores for the last 7 days
  /myscore      - personal score
"""

import json
import logging
import os
import sqlite3
from datetime import date, datetime, time, timedelta
from pathlib import Path
from zoneinfo import ZoneInfo

from dotenv import load_dotenv
from telegram import Update
from telegram.constants import PollType
from telegram.ext import (
    Application,
    CommandHandler,
    ContextTypes,
    PollAnswerHandler,
)

load_dotenv()

BOT_TOKEN = os.environ["TELEGRAM_BOT_TOKEN"]
CHAT_ID = int(os.environ["TELEGRAM_CHAT_ID"])
SEND_TIME = os.getenv("QUIZ_SEND_TIME", "08:00")  # HH:MM
TZ = ZoneInfo(os.getenv("TZ_NAME", "Asia/Jakarta"))

BASE_DIR = Path(__file__).parent
OUTPUT_DIR = BASE_DIR / "output"
DB_PATH = BASE_DIR / "quiz.db"

# Telegram length limits for quiz polls
MAX_QUESTION = 300
MAX_OPTION = 100
MAX_EXPLANATION = 200

logging.basicConfig(
    format="%(asctime)s %(levelname)s %(name)s: %(message)s", level=logging.INFO
)
log = logging.getLogger("quiz-bot")


# ---------------------------------------------------------------- database
def db() -> sqlite3.Connection:
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    return conn


def init_db() -> None:
    with db() as conn:
        conn.executescript(
            """
            CREATE TABLE IF NOT EXISTS polls (
                poll_id       TEXT PRIMARY KEY,
                quiz_date     TEXT NOT NULL,
                correct_index INTEGER NOT NULL,
                difficulty    TEXT
            );
            CREATE TABLE IF NOT EXISTS answers (
                poll_id     TEXT NOT NULL,
                user_id     INTEGER NOT NULL,
                username    TEXT,
                is_correct  INTEGER NOT NULL,
                answered_at TEXT NOT NULL,
                PRIMARY KEY (poll_id, user_id)
            );
            CREATE TABLE IF NOT EXISTS sent (
                quiz_date TEXT PRIMARY KEY
            );
            """
        )


# ------------------------------------------------------------- quiz file
def load_quiz(day: date) -> list[dict] | None:
    path = OUTPUT_DIR / f"quiz-{day.isoformat()}.json"
    if not path.exists():
        return None
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as e:
        log.error("Invalid JSON in %s: %s", path, e)
        return None

    valid = []
    for i, q in enumerate(data, 1):
        try:
            options = [str(o) for o in q["options"]]
            letter = str(q["answer"]).strip().upper()[0]
            correct = "ABCD".index(letter)
            if len(options) < 2 or correct >= len(options):
                raise ValueError("options/answer mismatch")
            valid.append(
                {
                    "question": str(q["question"]),
                    "options": options,
                    "correct": correct,
                    "explanation": str(q.get("explanation", "")),
                    "difficulty": q.get("difficulty", ""),
                    "language": str(q.get("language", "id")).lower(),
                }
            )
        except (KeyError, ValueError, IndexError) as e:
            log.warning("Question #%d skipped: %s", i, e)
    return valid or None


DIFFICULTY_EN = {"mudah": "easy", "sedang": "medium", "sulit": "hard"}


def difficulty_label(q: dict) -> str:
    """Difficulty label in the question's language; the DB value stays mudah/sedang/sulit."""
    diff = q["difficulty"]
    if not diff:
        return ""
    if q["language"] == "en":
        diff = DIFFICULTY_EN.get(diff, diff)
    return f"[{diff}] "


def cut(text: str, limit: int) -> str:
    return text if len(text) <= limit else text[: limit - 1] + "…"


# ------------------------------------------------------------- sending
async def send_quiz(context: ContextTypes.DEFAULT_TYPE, force: bool = False) -> str:
    today = datetime.now(TZ).date()

    with db() as conn:
        already = conn.execute(
            "SELECT 1 FROM sent WHERE quiz_date = ?", (today.isoformat(),)
        ).fetchone()
    if already and not force:
        return "Quiz hari ini sudah dikirim."

    questions = load_quiz(today)
    if not questions:
        await context.bot.send_message(
            CHAT_ID, "⚠️ Quiz hari ini belum tersedia. Cek job generator-nya ya."
        )
        return "File quiz tidak ditemukan / kosong."

    await context.bot.send_message(
        CHAT_ID,
        f"🧠 *Daily Quiz — {today.strftime('%d %b %Y')}*\n"
        f"{len(questions)} soal. Selamat mengerjakan!",
        parse_mode="Markdown",
    )

    for n, q in enumerate(questions, 1):
        label = difficulty_label(q)
        msg = await context.bot.send_poll(
            chat_id=CHAT_ID,
            question=cut(f"{n}. {label}{q['question']}", MAX_QUESTION),
            options=[cut(o, MAX_OPTION) for o in q["options"]],
            type=PollType.QUIZ,
            correct_option_id=q["correct"],
            explanation=cut(q["explanation"], MAX_EXPLANATION) or None,
            is_anonymous=False,  # required so answers can be recorded
        )
        with db() as conn:
            conn.execute(
                "INSERT OR REPLACE INTO polls VALUES (?, ?, ?, ?)",
                (msg.poll.id, today.isoformat(), q["correct"], q["difficulty"]),
            )

    with db() as conn:
        conn.execute("INSERT OR IGNORE INTO sent VALUES (?)", (today.isoformat(),))
    return f"Terkirim {len(questions)} soal."


async def scheduled_job(context: ContextTypes.DEFAULT_TYPE) -> None:
    result = await send_quiz(context)
    log.info("Scheduled send: %s", result)


# ------------------------------------------------------------- handlers
async def on_poll_answer(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    ans = update.poll_answer
    if not ans.option_ids:  # user retracted their vote
        return
    with db() as conn:
        row = conn.execute(
            "SELECT correct_index FROM polls WHERE poll_id = ?", (ans.poll_id,)
        ).fetchone()
        if row is None:
            return
        user = ans.user
        name = user.username or user.full_name
        conn.execute(
            "INSERT OR IGNORE INTO answers VALUES (?, ?, ?, ?, ?)",
            (
                ans.poll_id,
                user.id,
                name,
                int(ans.option_ids[0] == row["correct_index"]),
                datetime.now(TZ).isoformat(),
            ),
        )


async def cmd_start(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    await update.message.reply_text(
        "Halo! Saya Daily Quiz Bot 🧠\n"
        f"Quiz dikirim tiap hari kerja pukul {SEND_TIME} WIB.\n\n"
        "/leaderboard — skor 7 hari terakhir\n"
        "/myscore — skor kamu\n"
        "/quiz — kirim quiz hari ini sekarang"
    )


async def cmd_quiz(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    result = await send_quiz(context)
    await update.message.reply_text(result)


async def cmd_leaderboard(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    since = (datetime.now(TZ).date() - timedelta(days=7)).isoformat()
    with db() as conn:
        rows = conn.execute(
            """
            SELECT a.username, SUM(a.is_correct) AS correct, COUNT(*) AS total
            FROM answers a JOIN polls p ON p.poll_id = a.poll_id
            WHERE p.quiz_date >= ?
            GROUP BY a.user_id
            ORDER BY correct DESC, total ASC
            LIMIT 10
            """,
            (since,),
        ).fetchall()
    if not rows:
        await update.message.reply_text("Belum ada jawaban minggu ini.")
        return
    medals = ["🥇", "🥈", "🥉"]
    lines = ["🏆 *Leaderboard 7 hari terakhir*\n"]
    for i, r in enumerate(rows):
        icon = medals[i] if i < 3 else f"{i + 1}."
        lines.append(f"{icon} {r['username']} — {r['correct']}/{r['total']}")
    await update.message.reply_text("\n".join(lines), parse_mode="Markdown")


async def cmd_myscore(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    uid = update.effective_user.id
    with db() as conn:
        r = conn.execute(
            "SELECT SUM(is_correct) AS correct, COUNT(*) AS total "
            "FROM answers WHERE user_id = ?",
            (uid,),
        ).fetchone()
    if not r["total"]:
        await update.message.reply_text("Kamu belum menjawab quiz apa pun.")
        return
    pct = r["correct"] / r["total"] * 100
    await update.message.reply_text(
        f"Skor kamu: {r['correct']}/{r['total']} benar ({pct:.0f}%)"
    )


# ------------------------------------------------------------- main
def main() -> None:
    init_db()
    OUTPUT_DIR.mkdir(exist_ok=True)

    app = Application.builder().token(BOT_TOKEN).build()
    app.add_handler(CommandHandler("start", cmd_start))
    app.add_handler(CommandHandler("quiz", cmd_quiz))
    app.add_handler(CommandHandler("leaderboard", cmd_leaderboard))
    app.add_handler(CommandHandler("myscore", cmd_myscore))
    app.add_handler(PollAnswerHandler(on_poll_answer))

    hh, mm = map(int, SEND_TIME.split(":"))
    app.job_queue.run_daily(
        scheduled_job,
        time=time(hh, mm, tzinfo=TZ),
        days=(1, 2, 3, 4, 5),  # Monday–Friday
        name="matriq-quiz",
    )

    log.info("Bot running. Quiz scheduled at %s (%s).", SEND_TIME, TZ)
    app.run_polling(allowed_updates=Update.ALL_TYPES)


if __name__ == "__main__":
    main()
